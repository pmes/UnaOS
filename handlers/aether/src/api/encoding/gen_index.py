#!/usr/bin/env python3
# AETHERWPT3 (LEDGER SR138): generates index.rs — the Encoding Standard's indexes (§5) as Rust tables — from the
# WHATWG index JSON. Run from this directory:
#
#   B=https://raw.githubusercontent.com/whatwg/encoding/a985b62a9b45c17da3e17a9f0a0b4e30c34c4a8a
#   curl -sSo indexes.json $B/indexes.json; curl -sSo encodings.json $B/encodings.json
#   sha256sum indexes.json   # b7c8961095f0b4cae8f4a16a5011e7c84047a60c1277e28ee8df9e56074ee509
#   python3 -I gen_index.py indexes.json encodings.json > index.rs
#
# Layout: a pointer's code point is TABLE[pointer]; 0 is "null" (U+0000 is in no index). Big5 holds code points
# above U+FFFF, so it is u32; every other multi-byte index fits u16. The single-byte indexes are one row of 128
# per encoding, in the order of SINGLE_BYTE_NAMES.
import json
import sys

src = sys.argv[1]
d = json.load(open(src, encoding='utf-8'))
encodings = json.load(open(sys.argv[2], encoding='utf-8'))
out = []
w = out.append
w('// GENERATED by gen_index.py from the WHATWG Encoding Standard indexes.json')
w('// (whatwg/encoding a985b62a9b45c17da3e17a9f0a0b4e30c34c4a8a, sha256 b7c8961095f0b4cae8f4a16a5011e7c84047a60c1277e28ee8df9e56074ee509) — do not edit.')
w('//! The Encoding Standard §4.2 label table (encodings.json) and §5 indexes: pointer → code point, 0 = null.')
w('#![allow(clippy::unreadable_literal)]')
w('')

def table(name, ty, values):
    vals = [0 if v is None else v for v in values]
    w(f'pub static {name}: [{ty}; {len(vals)}] = [')
    for i in range(0, len(vals), 24):
        w('    ' + ','.join(str(v) for v in vals[i:i + 24]) + ',')
    w('];')
    w('')

rows = [(e['name'], e['labels']) for g in encodings for e in g['encodings']]
w(f'pub static LABELS: [(&str, &[&str]); {len(rows)}] = [')
for name, labels in rows:
    w('    ("%s", &[%s]),' % (name, ', '.join('"%s"' % l for l in labels)))
w('];')
w('')

singles = sorted(k for k, v in d.items() if isinstance(v, list) and len(v) == 128 and k != 'iso-2022-jp-katakana')
w(f'pub static SINGLE_BYTE_NAMES: [&str; {len(singles)}] = [' + ', '.join(f'"{n}"' for n in singles) + '];')
w('')
w(f'pub static SINGLE_BYTE: [[u16; 128]; {len(singles)}] = [')
for n in singles:
    vals = [0 if v is None else v for v in d[n]]
    w('    [' + ','.join(str(v) for v in vals) + '],')
w('];')
w('')
table('JIS0208', 'u16', d['jis0208'])
table('JIS0212', 'u16', d['jis0212'])
table('EUC_KR', 'u16', d['euc-kr'])
table('GB18030', 'u16', d['gb18030'])
table('BIG5', 'u32', d['big5'])
table('ISO2022JP_KATAKANA', 'u16', d['iso-2022-jp-katakana'])
ranges = d['gb18030-ranges']
w(f'pub static GB18030_RANGES: [(u32, u32); {len(ranges)}] = [')
for i in range(0, len(ranges), 8):
    w('    ' + ' '.join(f'({a}, {b}),' for a, b in ranges[i:i + 8]))
w('];')
sys.stdout.write('\n'.join(out) + '\n')
