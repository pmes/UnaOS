//! HTML §2.6.1 reflection (AETHERWPT SR72; table-driven since AETHERREFLECT SR81): every reflected IDL
//! attribute of the HTML element interfaces, by the algorithm its type names — DOMString (with
//! [LegacyNullToEmptyString] where the IDL says so), nullable DOMString (the ARIA mixin), USVString
//! reflecting a URL, boolean, enumerated limited to known values (keywords, missing value default, invalid
//! value default, non-canonical aliases; nullable for `crossOrigin` and the ARIA mixin), long, long limited
//! to non-negative, unsigned long, unsigned long limited to positive (throwing or with fallback), clamped
//! unsigned long, double and double limited to positive.
//!
//! WHICH attributes reflect, and how, is data: `reflect_table.rs`, generated by
//! `handlers/aether/tools/gen_reflect_table.py` from WPT's own reflection tables (`html/dom/elements-*.js`
//! and reflection.js's global loop) plus the Standard's rows the tables omit. This file is the one
//! implementation per kind. Installed after `html::install`, it supersedes that file's short table for the
//! names it lists; anything with behaviour beyond reflection (input.value, option.label, …) is installed
//! later by `controls::install` and wins.

use super::dom::{self, attr_value, remove_attr, set_attr, this_element};
use super::idl::*;
use super::reflect_table::ROWS;
use js_core::vm::*;

/// An enumerated attribute limited to only known values (HTML §2.3.3, §2.6.1).
#[derive(Debug)]
pub struct En {
    /// The keywords in their canonical case (`""` may be one of them: referrerPolicy).
    pub keywords: &'static [&'static str],
    /// The missing value default; `None` is the null state (nullable attributes only) / no state.
    pub missing: Option<&'static str>,
    /// The invalid value default.
    pub invalid: Option<&'static str>,
    /// `DOMString?`: null on getting the null state, and setting null removes the attribute.
    pub nullable: bool,
    /// Non-canonical values: a content value matching `.0` (ASCII case-insensitively) is in state `.1`.
    pub aliases: &'static [(&'static str, Option<&'static str>)],
}

/// One reflection kind of HTML §2.6.1 with its defaults and limits.
#[derive(Debug)]
pub enum Kind {
    Str,
    /// DOMString with [LegacyNullToEmptyString].
    StrNull,
    /// `DOMString?` reflecting a plain attribute: absent is null, setting null removes it.
    NullableStr,
    Url,
    /// `form.action` / `formAction`: a URL whose absent or empty value is the document's URL (§4.10.18.6).
    Action,
    Bool,
    /// `hidden`: boolean, or the "until-found" state.
    Hidden,
    /// `tabIndex`: a long whose default is the element's default focusability (§6.6.3).
    TabIndex,
    /// long, default.
    Long(i64),
    /// long limited to only non-negative numbers, default.
    LimLong(i64),
    /// unsigned long, default.
    ULong(i64),
    /// unsigned long limited to only positive numbers (setting 0 throws), default.
    LimULong(i64),
    /// unsigned long limited to only positive numbers with fallback, default.
    LimULongFb(i64),
    /// unsigned long clamped to [min, max], default.
    Clamped { min: i64, max: i64, default: i64 },
    /// double, default.
    Double(f64),
    /// double limited to only positive numbers, default.
    LimDouble(f64),
    Enum(&'static En),
}

/// Where a row lives: a tag (its interface is `html::interface_for_tag(tag)`) or a named interface.
#[derive(Debug)]
pub enum On {
    Tag(&'static str),
    Iface(&'static str),
}

/// One reflected IDL attribute.
#[derive(Debug)]
pub struct Row {
    pub on: On,
    pub idl: &'static str,
    pub attr: &'static str,
    pub kind: Kind,
}

const MAX_INT: i64 = 2147483647;

/// "rules for parsing integers" (HTML §2.3.4.1); None on error.
pub fn parse_int(s: &str) -> Option<i64> {
    let t = s.trim_start_matches([' ', '\t', '\n', '\x0C', '\r']);
    let (neg, rest) = match t.as_bytes().first() {
        Some(b'-') => (true, &t[1..]),
        Some(b'+') => (false, &t[1..]),
        _ => (false, t),
    };
    let digits: &str = &rest[..rest.bytes().take_while(|c| c.is_ascii_digit()).count()];
    if digits.is_empty() {
        return None;
    }
    let mut v: i64 = 0;
    for c in digits.bytes() {
        v = v.saturating_mul(10).saturating_add((c - b'0') as i64);
        if v > 1 << 40 {
            v = 1 << 40;
        }
    }
    Some(if neg { -v } else { v })
}

fn parse_nonneg(s: &str) -> Option<i64> {
    parse_int(s).filter(|v| *v >= 0)
}

/// "rules for parsing floating-point number values" (HTML §2.3.4.3); None on error.
pub fn parse_float(s: &str) -> Option<f64> {
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() && matches!(b[i], b' ' | b'\t' | b'\n' | 0x0C | b'\r') {
        i += 1;
    }
    if i >= b.len() {
        return None;
    }
    let mut sign = 1.0;
    if b[i] == b'-' {
        sign = -1.0;
        i += 1;
    } else if b[i] == b'+' {
        i += 1;
    }
    if i >= b.len() {
        return None;
    }
    let start = i;
    let mut txt = String::new();
    if b[i] == b'.' && i + 1 < b.len() && b[i + 1].is_ascii_digit() {
        txt.push('0');
    } else if !b[i].is_ascii_digit() {
        return None;
    } else {
        while i < b.len() && b[i].is_ascii_digit() {
            i += 1;
        }
        txt.push_str(&s[start..i]);
    }
    if i < b.len() && b[i] == b'.' {
        let f0 = i;
        i += 1;
        while i < b.len() && b[i].is_ascii_digit() {
            i += 1;
        }
        if i > f0 + 1 {
            txt.push_str(&s[f0..i]);
        }
    }
    if i < b.len() && (b[i] == b'e' || b[i] == b'E') {
        let mut j = i + 1;
        let mut exp = String::from("e");
        if j < b.len() && (b[j] == b'-' || b[j] == b'+') {
            exp.push(b[j] as char);
            j += 1;
        }
        let d0 = j;
        while j < b.len() && b[j].is_ascii_digit() {
            j += 1;
        }
        if j > d0 {
            exp.push_str(&s[d0..j]);
            txt.push_str(&exp);
        }
    }
    let v: f64 = txt.parse().ok()?;
    let v = sign * v;
    if !v.is_finite() {
        return None;
    }
    Some(if v == 0.0 { 0.0 } else { v })
}

fn doc_url_of(d: usize) -> String {
    let u = super::page(|p| p.docs.get(&d).map(|m| m.url.clone())).unwrap_or_else(super::page_url);
    if u.is_empty() { "about:blank".into() } else { u }
}


fn row(vm: &Vm, ctx: &CallCtx) -> &'static Row {
    match vm.native_slot(ctx.callee, 0) {
        Value::Number(n) => &ROWS[n as usize],
        _ => &ROWS[0],
    }
}

/// The state an enumerated attribute is in (HTML §2.3.3), as its canonical keyword; None is the null
/// state (or no state).
fn enum_state(e: &En, v: Option<String>) -> Option<&'static str> {
    let Some(v) = v else { return e.missing };
    for (from, to) in e.aliases {
        if v.eq_ignore_ascii_case(from) {
            return *to;
        }
    }
    for k in e.keywords {
        if v.eq_ignore_ascii_case(k) {
            return Some(*k);
        }
    }
    e.invalid
}

/// The default tabIndex: 0 for elements focusable by default, else -1.
fn default_tab_index(el: usize) -> i64 {
    let tag = dom::with_doc(|d| dom::local_name_in(d, el));
    let focusable = match tag.as_str() {
        "a" | "area" => attr_value(el, "href").is_some(),
        "button" | "input" | "select" | "textarea" | "iframe" | "frame" | "object" | "embed" => true,
        "summary" => true,
        _ => false,
    };
    if focusable || attr_value(el, "contenteditable").is_some() {
        0
    } else {
        -1
    }
}


/// A long-family value in range of a 32-bit long, else None.
fn in_long(n: i64) -> Option<i64> {
    (i32::MIN as i64..=MAX_INT).contains(&n).then_some(n)
}

fn reflect_get(vm: &mut Vm, ctx: &CallCtx) -> JsResult<Value> {
    let el = this_element(vm, ctx)?;
    let r = row(vm, ctx);
    let v = attr_value(el, r.attr);
    Ok(match &r.kind {
        Kind::Str | Kind::StrNull => s(&v.unwrap_or_default()),
        Kind::NullableStr => match v {
            Some(x) => s(&x),
            None => Value::Null,
        },
        Kind::Bool => Value::Bool(v.is_some()),
        Kind::Hidden => match v {
            Some(x) if x.eq_ignore_ascii_case("until-found") => s("until-found"),
            x => Value::Bool(x.is_some()),
        },
        Kind::Url => match v {
            Some(x) => s(&dom::resolve_url(dom::node_document(el), &x).unwrap_or(x)),
            None => s(""),
        },
        Kind::Action => match v.filter(|x| !x.is_empty()) {
            Some(x) => s(&dom::resolve_url(dom::node_document(el), &x).unwrap_or(x)),
            None => s(&doc_url_of(dom::node_document(el))),
        },
        Kind::Long(d) => num(v.and_then(|x| parse_int(&x)).and_then(in_long).unwrap_or(*d) as f64),
        Kind::TabIndex => num(v.and_then(|x| parse_int(&x)).and_then(in_long).unwrap_or_else(|| default_tab_index(el)) as f64),
        Kind::LimLong(d) | Kind::ULong(d) => num(v.and_then(|x| parse_nonneg(&x)).filter(|n| *n <= MAX_INT).unwrap_or(*d) as f64),
        Kind::LimULong(d) | Kind::LimULongFb(d) => num(v.and_then(|x| parse_nonneg(&x)).filter(|n| (1..=MAX_INT).contains(n)).unwrap_or(*d) as f64),
        Kind::Clamped { min, max, default } => num(match v.and_then(|x| parse_nonneg(&x)) {
            None => *default,
            Some(n) => n.clamp(*min, *max),
        } as f64),
        Kind::Double(d) => num(v.and_then(|x| parse_float(&x)).unwrap_or(*d)),
        Kind::LimDouble(d) => num(v.and_then(|x| parse_float(&x)).filter(|n| *n > 0.0).unwrap_or(*d)),
        Kind::Enum(e) => match enum_state(e, v) {
            Some(x) => s(x),
            None => Value::Null,
        },
    })
}

fn set_bool(vm: &mut Vm, el: usize, attr: &str, on: bool) {
    if on {
        set_attr(vm, el, attr, "");
    } else {
        remove_attr(vm, el, attr);
    }
}

fn reflect_set(vm: &mut Vm, ctx: &CallCtx) -> JsResult<Value> {
    let el = this_element(vm, ctx)?;
    let r = row(vm, ctx);
    let attr = r.attr;
    let v = arg(vm, ctx, 0);
    match &r.kind {
        Kind::Str | Kind::Url | Kind::Action => {
            let x = string(vm, &v)?;
            set_attr(vm, el, attr, &x);
        }
        Kind::StrNull => {
            let x = string_null_empty(vm, &v)?;
            set_attr(vm, el, attr, &x);
        }
        Kind::NullableStr | Kind::Enum(En { nullable: true, .. }) if v.is_nullish() => remove_attr(vm, el, attr),
        Kind::NullableStr | Kind::Enum(_) => {
            // Limited to known values or not, setting stores the given value (HTML §2.6.1).
            let x = string(vm, &v)?;
            set_attr(vm, el, attr, &x);
        }
        Kind::Bool => {
            let b = vm.to_boolean(&v);
            set_bool(vm, el, attr, b);
        }
        Kind::Hidden => {
            if let Value::String(x) = &v {
                if x.to_rust().eq_ignore_ascii_case("until-found") {
                    set_attr(vm, el, attr, "until-found");
                    return Ok(Value::Undefined);
                }
            }
            let b = vm.to_boolean(&v);
            set_bool(vm, el, attr, b);
        }
        Kind::Long(_) | Kind::TabIndex => {
            let n = vm.to_int32(&v)?;
            set_attr(vm, el, attr, &n.to_string());
        }
        Kind::LimLong(_) => {
            let n = vm.to_int32(&v)?;
            if n < 0 {
                return throw_dom(vm, "IndexSizeError", "The value provided is negative.");
            }
            set_attr(vm, el, attr, &n.to_string());
        }
        Kind::ULong(d) | Kind::Clamped { default: d, .. } => {
            let n = vm.to_uint32(&v)? as i64;
            set_attr(vm, el, attr, &(if n <= MAX_INT { n } else { *d }).to_string());
        }
        Kind::LimULong(d) => {
            let n = vm.to_uint32(&v)? as i64;
            if n == 0 {
                return throw_dom(vm, "IndexSizeError", "The value provided is 0, which is an invalid size.");
            }
            set_attr(vm, el, attr, &(if n <= MAX_INT { n } else { *d }).to_string());
        }
        Kind::LimULongFb(d) => {
            let n = vm.to_uint32(&v)? as i64;
            set_attr(vm, el, attr, &(if (1..=MAX_INT).contains(&n) { n } else { *d }).to_string());
        }
        Kind::Double(_) | Kind::LimDouble(_) => {
            let n = vm.to_number(&v)?;
            if !n.is_finite() {
                return vm.throw_type("The provided double value is non-finite.");
            }
            if matches!(r.kind, Kind::LimDouble(_)) && n <= 0.0 {
                return Ok(Value::Undefined);
            }
            let t = vm.to_string(&Value::Number(n))?.to_rust();
            set_attr(vm, el, attr, &t);
        }
    }
    Ok(Value::Undefined)
}

// ------------------------------------------------------------------------------------------------ Document color/dir reflection

fn doc_reflect_target(vm: &mut Vm, ctx: &CallCtx) -> JsResult<Option<usize>> {
    let Some(d) = dom::node_of(vm, &ctx.this).filter(|n| dom::kind(*n) == dom::NK::Document) else {
        return vm.throw_type("Illegal invocation");
    };
    let which = callee_str(vm, ctx);
    Ok(if which == "dir" { dom::document_element_of(d) } else { dom::body_of(d).filter(|b| dom::with_doc(|doc| dom::is_html_tag(doc, *b, "body"))) })
}

fn doc_attr_name(which: &str) -> &'static str {
    match which {
        "dir" => "dir",
        "fgColor" => "text",
        "linkColor" => "link",
        "vlinkColor" => "vlink",
        "alinkColor" => "alink",
        _ => "bgcolor",
    }
}

fn doc_reflect_get(vm: &mut Vm, ctx: &CallCtx) -> JsResult<Value> {
    let which = callee_str(vm, ctx);
    let Some(el) = doc_reflect_target(vm, ctx)? else { return Ok(s("")) };
    let v = attr_value(el, doc_attr_name(&which)).unwrap_or_default();
    if which == "dir" {
        let l = v.to_ascii_lowercase();
        return Ok(s(if matches!(l.as_str(), "ltr" | "rtl" | "auto") { &l } else { "" }));
    }
    Ok(s(&v))
}

fn doc_reflect_set(vm: &mut Vm, ctx: &CallCtx) -> JsResult<Value> {
    let which = callee_str(vm, ctx);
    let v = arg(vm, ctx, 0);
    let x = if which == "dir" { string(vm, &v)? } else { string_null_empty(vm, &v)? };
    if let Some(el) = doc_reflect_target(vm, ctx)? {
        set_attr(vm, el, doc_attr_name(&which), &x);
    }
    Ok(Value::Undefined)
}


/// The interface a row's accessor goes on.
fn row_iface(r: &Row) -> &'static str {
    match r.on {
        On::Tag(t) => super::html::interface_for_tag(t),
        On::Iface(i) => i,
    }
}

pub fn install(vm: &mut Vm) {
    // Tags sharing an interface (h1–h6, td/th, ins/del, …) name the same attribute once per tag: the
    // first row for an (interface, IDL name) is the one installed.
    let mut done = std::collections::HashSet::new();
    for (i, r) in ROWS.iter().enumerate() {
        let name = row_iface(r);
        if !done.insert((name, r.idl)) {
            continue;
        }
        let Some(iface) = dom::iface(name) else { continue };
        attr_with(vm, iface.proto, r.idl, reflect_get, Some(reflect_set), num(i as f64));
    }
    let dp = dom::proto("Document");
    for w in ["dir", "fgColor", "linkColor", "vlinkColor", "alinkColor", "bgColor"] {
        attr_with(vm, dp, w, doc_reflect_get, Some(doc_reflect_set), s(w));
    }
}
