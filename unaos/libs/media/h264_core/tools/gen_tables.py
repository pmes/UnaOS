def zigzag(n):
    order = []
    for d in range(2 * n - 1):
        cells = [(x, d - x) for x in range(n) if 0 <= d - x < n]
        # even diagonal: from bottom-left to top-right (x increasing); odd: top-right to bottom-left
        if d % 2 == 0:
            cells.sort(key=lambda c: c[0])
        else:
            cells.sort(key=lambda c: -c[0])
        for (x, y) in cells:
            order.append(y * n + x)
    return order

