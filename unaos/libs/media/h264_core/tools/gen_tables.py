def parse_rows(text, rows, cols):
    tab = []
    for line in text.strip().splitlines():
        cells = line.split()
        if len(cells) != cols:
            fail("row has %d cells: %r" % (len(cells), line))
        tab.append([c if c != "-" else "" for c in cells])
    if len(tab) != rows:
        fail("table has %d rows, wants %d" % (len(tab), rows))
    return tab

def check_prefix_free(codes, name, complete):
    codes = [c for c in codes if c]
    for a in codes:
        for b in codes:
            if a is not b and b.startswith(a):
                fail("%s: %s is a prefix of %s" % (name, a, b))
    kraft = sum(2.0 ** -len(c) for c in codes)
    if complete and abs(kraft - 1.0) > 1e-12:
        fail("%s: Kraft sum %r, code incomplete" % (name, kraft))
    return kraft

