emit("KF_YMODE_PROBS", "u8", [4], array("vp8_kf_ymode_prob", "vp8_entropymodedata.h"))
emit("KF_UV_MODE_PROBS", "u8", [3], array("vp8_kf_uv_mode_prob", "vp8_entropymodedata.h"))
emit("YMODE_PROBS", "u8", [4], array("vp8_ymode_prob", "vp8_entropymodedata.h"))
emit("UV_MODE_PROBS", "u8", [3], array("vp8_uv_mode_prob", "vp8_entropymodedata.h"))
emit("BMODE_PROBS", "u8", [9], array("vp8_bmode_prob", "vp8_entropymodedata.h"))
emit("MV_UPDATE_PROBS", "u8", [2, 19], array("vp8_mv_update_probs", "entropymv.c"))
