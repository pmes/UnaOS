//! CHARTER: shared-core (text)
//!
//! PDF3 (LEDGER SR314): Type 1 fonts (Adobe Type 1 Font Format 1.1) beside the CFF Type 2 reader in [`crate::cff`].
//! [`Type1Font::parse`] reads a font program as PFB (segment headers), PFA (hex after `eexec`) or the raw form a PDF
//! `/FontFile` carries (cleartext, then binary after `eexec`); undoes eexec encryption (r = 55665, c1 = 52845,
//! c2 = 22719, four lead bytes); reads `/FontMatrix`, `/FontName`, `/Encoding` (`StandardEncoding` or the
//! `dup <code> /<name> put` array), `/lenIV`, `/Subrs` and `/CharStrings` (each decrypted with r = 4330).
//! [`Type1Font::outline`] is the Type 1 charstring interpreter: hsbw sbw rmoveto hmoveto vmoveto rlineto hlineto
//! vlineto rrcurveto hvcurveto vhcurveto closepath callsubr return endchar div callothersubr (0/1/2 flex, 3 hint
//! replacement, others pass their arguments through) pop setcurrentpoint seac; the stem hints (hstem vstem hstem3
//! vstem3 dotsection) are consumed and not applied (no hinting). Outlines go to the same [`OutlineSink`] the glyf
//! and CFF readers feed. Bounded: subroutine depth 10, 100 000 operators per glyph, every read checked.

