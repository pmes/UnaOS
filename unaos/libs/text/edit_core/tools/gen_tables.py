#!/usr/bin/env python3
# EDITCORE (LEDGER SR73): generates edit_core's Unicode tables from the UCD 17.0.0 data files — DATA ONLY.
#
# Usage (run from unaos/libs/text/edit_core):
#     python3 -I tools/gen_tables.py <ucd-dir>
# where <ucd-dir> holds the six files below, fetched from Unicode's own source repository (www.unicode.org is
# refused by this bench's egress proxy; the unicodetools repo is where those files are authored):
#     https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/17.0.0/<path>
# The sha256 of every input is checked against the pins below (the first four are the same pins font_core's
# oracle/vectors.txt carries for the same files) and written into the header of each output.
#
# Writes:
#   src/tables.rs              Grapheme_Cluster_Break, Word_Break, Extended_Pictographic, Indic_Conjunct_Break
#                              as sorted, merged (lo, hi, value) range tables + the value codes.
#   tests/data/grapheme_test.txt, tests/data/word_test.txt
#                              GraphemeBreakTest / WordBreakTest with the comments cut (the boundary marks and
#                              code points only) — the UAX #29 conformance vectors the tests replay offline.
import hashlib
import os
import sys

PINS = {
    'GraphemeBreakProperty.txt': 'd6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89',
    'emoji-data.txt': '2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b',
    'DerivedCoreProperties.txt': '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08',
    'GraphemeBreakTest.txt': 'e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec',
    'WordBreakProperty.txt': '72274cac1e6b919507db35655c3e175aa27274668a1ece95c28d2069f2ad9852',
    'WordBreakTest.txt': '1de23a75f37904abc7d206239ee8d34f8fdf0fb4ab32a7174dfbabbde25419b2',
}

GCB = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend', 'SpacingMark',
       'L', 'V', 'T', 'LV', 'LVT']
WB = ['Other', 'CR', 'LF', 'Newline', 'Extend', 'ZWJ', 'Regional_Indicator', 'Format', 'Katakana',
      'Hebrew_Letter', 'ALetter', 'Single_Quote', 'Double_Quote', 'MidNumLet', 'MidLetter', 'MidNum',
      'Numeric', 'ExtendNumLet', 'WSegSpace']
INCB = ['None', 'Consonant', 'Extend', 'Linker']


def read(d, name):
    data = open(os.path.join(d, name), 'rb').read()
    h = hashlib.sha256(data).hexdigest()
    if h != PINS[name]:
        sys.exit('%s: sha256 %s != pinned %s' % (name, h, PINS[name]))
    return data.decode('utf-8'), h


def rows(text):
    for line in text.splitlines():
        body = line.split('#')[0].strip()
        if not body:
            continue
        f = [x.strip() for x in body.split(';')]
        r = f[0]
        if '..' in r:
            a, b = r.split('..')
            lo, hi = int(a, 16), int(b, 16)
        else:
            lo = hi = int(r, 16)
        yield lo, hi, f[1:]


def ranges(pairs):
    """[(lo, hi, v)] -> sorted, adjacent same-value ranges merged."""
    pairs.sort()
    out = []
    for lo, hi, v in pairs:
        if out and out[-1][2] == v and out[-1][1] + 1 == lo:
            out[-1] = (out[-1][0], hi, v)
        else:
            out.append((lo, hi, v))
    for i in range(1, len(out)):
        assert out[i - 1][1] < out[i][0], 'overlap at %x' % out[i][0]
    return out


def emit_table(w, name, rs, names):
    w('pub(crate) static %s: &[(u32, u32, u8)] = &[\n' % name)
    for lo, hi, v in rs:
        w('    (0x%04X, 0x%04X, %d), // %s\n' % (lo, hi, v, names[v]))
    w('];\n\n')


def emit_set(w, name, rs):
    w('pub(crate) static %s: &[(u32, u32)] = &[\n' % name)
    for lo, hi, _ in rs:
        w('    (0x%04X, 0x%04X),\n' % (lo, hi))
    w('];\n\n')


def compact_test(text):
    out = []
    for line in text.splitlines():
        body = line.split('#')[0].strip()
        if body:
            out.append(body)
    return '\n'.join(out) + '\n'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__ or 'usage: gen_tables.py <ucd-dir>')
    d = sys.argv[1]
    gtext, gh = read(d, 'GraphemeBreakProperty.txt')
    etext, eh = read(d, 'emoji-data.txt')
    dtext, dh = read(d, 'DerivedCoreProperties.txt')
    wtext, wh = read(d, 'WordBreakProperty.txt')
    gt, gth = read(d, 'GraphemeBreakTest.txt')
    wt, wth = read(d, 'WordBreakTest.txt')

    gcb = ranges([(lo, hi, GCB.index(f[0])) for lo, hi, f in rows(gtext)])
    wb = ranges([(lo, hi, WB.index(f[0])) for lo, hi, f in rows(wtext)])
    ep = ranges([(lo, hi, 1) for lo, hi, f in rows(etext) if f[0] == 'Extended_Pictographic'])
    incb = ranges([(lo, hi, INCB.index(f[1])) for lo, hi, f in rows(dtext) if f[0] == 'InCB'])

    out = []
    w = out.append
    w('// GENERATED by tools/gen_tables.py from UCD 17.0.0 — DATA ONLY, do not edit by hand.\n')
    w('// Inputs (sha256):\n')
    for n, h in [('GraphemeBreakProperty.txt', gh), ('WordBreakProperty.txt', wh),
                 ('emoji-data.txt', eh), ('DerivedCoreProperties.txt', dh)]:
        w('//   %s  %s\n' % (n, h))
    w('// Every table is sorted by code point, ranges inclusive and disjoint; a code point in no range has value 0.\n')
    w('#![allow(dead_code)] // the value-0 codes are named for the reader; lookup returns 0 by default\n\n')
    w('pub(crate) const UNICODE_VERSION: (u8, u8, u8) = (17, 0, 0);\n\n')
    for prefix, names in [('GCB', GCB), ('WB', WB), ('INCB', INCB)]:
        for i, n in enumerate(names):
            w('pub(crate) const %s_%s: u8 = %d;\n' % (prefix, n.upper(), i))
        w('\n')
    emit_table(w, 'GRAPHEME_BREAK', gcb, GCB)
    emit_table(w, 'WORD_BREAK', wb, WB)
    emit_table(w, 'INDIC_CONJUNCT_BREAK', incb, INCB)
    emit_set(w, 'EXTENDED_PICTOGRAPHIC', ep)
    open('src/tables.rs', 'w').write(''.join(out))

    os.makedirs('tests/data', exist_ok=True)
    hdr = '# GENERATED by tools/gen_tables.py: %s (sha256 %s) with comments cut — data only.\n'
    open('tests/data/grapheme_test.txt', 'w').write(hdr % ('GraphemeBreakTest-17.0.0.txt', gth) + compact_test(gt))
    open('tests/data/word_test.txt', 'w').write(hdr % ('WordBreakTest-17.0.0.txt', wth) + compact_test(wt))
    print('tables: gcb=%d wb=%d incb=%d extpict=%d ranges' % (len(gcb), len(wb), len(incb), len(ep)))


if __name__ == '__main__':
    main()
