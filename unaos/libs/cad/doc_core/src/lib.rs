/// The word for `v` in `table` (every enum value has one).
pub(crate) fn word_of<T: Copy + PartialEq>(table: &[(&'static str, T)], v: T) -> &'static str {
    table.iter().find(|(_, t)| *t == v).map(|(w, _)| *w).unwrap_or("?")
}

/// The value `w` names in `table`.
pub(crate) fn of_word<T: Copy>(table: &[(&'static str, T)], w: &str) -> Option<T> {
    table.iter().find(|(n, _)| *n == w).map(|(_, t)| *t)
}
