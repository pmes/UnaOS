//! CHARTER: Vug (CODEX §2, 3D, "CAD viewing, editing, and CAM/Slicing") — shared-core: doc_core, the design document.
//!
//! `doc_core` (VUGDOC, LEDGER SR480) is the ONE persistent artefact of the CAD program (docs/dev/USERLAND/VUG.md §5,
//! BP-vug-6: "the native document is a text form a diff can read"): UTF-8 text, one statement per line, no binary
//! section, that stores INTENT and never derived geometry —
//! sketches (their entities and the nineteen sketch_core constraints), features by name (extrude, revolve) with their
//! parameters, the Make (ONE machine by name with its declarative model, the Ops each on a feature: BP-vug-3) and scan
//! references (path, pose source, confidence; a path is data, never opened: BP-vug-4). The solved sketch, the Brep and
//! the Program are REGENERATED by [`replay`] through sketch_core, brep_core and make_core.
//!
//! * [`read`] — the text to a [`Doc`]; every refusal names its line and 1-based byte column ([`Refusal`]).
//! * [`write`] — a [`Doc`] to text, deterministic byte for byte (a fixed key order per verb, [`f64_text`] for every
//!   number, [`escape`] for every string).
//! * [`replay`] — the [`Doc`] through the cores: a statement that fails to regenerate stays in the document and is
//!   reported by its line ([`Failure`]), never dropped.
//!
//! The grammar: `<verb> <id>? <key>=<value>...`; `#` starts a comment (outside a string) that runs to the end of the
//! line; the first statement is the header `vug-doc version=1 lin=<f64> ang=<f64>` (the format, its version and the
//! one `Tol`, BP-vug-2). A value is a string `"..."` (the ONE escaping rule: `\\` `\"` `\n` `\r` `\t` `\u{HEX}`), a
//! list `[v v ...]`, or a word typed by its key. Every reference is a stable TEXT id declared on an EARLIER line (the
//! document is in dependency order), in ONE namespace; a sketch profile is selected by an entity id of its outer loop,
//! never by an index. Line shape after timeline_core's `edl::parse` and the cursor shape after pdf_core's `Lexer`
//! (cited, not copied).

