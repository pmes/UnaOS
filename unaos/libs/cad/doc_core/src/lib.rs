/// A point of a sketch by text id: a Point entity, or a circle's / arc's centre, or a line's / arc's start / end
/// (written `<id>`, `<id>.centre`, `<id>.start`, `<id>.end`).
#[derive(Clone, Debug, PartialEq)]
pub enum PRef {
    Point(String),
    Centre(String),
    Start(String),
    End(String),
}

/// sketch_core's nineteen constraints with TEXT references (sketch_core's own take `EntityId`s, minted at replay).
#[derive(Clone, Debug, PartialEq)]
pub enum Cons {
    Coincident(PRef, PRef),
    PointOnLine(PRef, String),
    PointOnCircle(PRef, String),
    Horizontal(String),
    Vertical(String),
    Parallel(String, String),
    Perpendicular(String, String),
    TangentLineCircle(String, String),
    TangentCircles(String, String),
    EqualLength(String, String),
    EqualRadius(String, String),
    Distance(PRef, PRef, f64),
    DistancePointLine(PRef, String, f64),
    Angle(String, String, f64),
    Radius(String, f64),
    Diameter(String, f64),
    Fix(PRef, [f64; 2]),
    Midpoint(PRef, String),
    Symmetric(PRef, PRef, String),
}

impl Cons {
    /// The statement verb.
    pub fn verb(&self) -> &'static str {
        match self {
            Cons::Coincident(..) => "coincident",
            Cons::PointOnLine(..) => "on_line",
            Cons::PointOnCircle(..) => "on_circle",
            Cons::Horizontal(..) => "horizontal",
            Cons::Vertical(..) => "vertical",
            Cons::Parallel(..) => "parallel",
            Cons::Perpendicular(..) => "perpendicular",
            Cons::TangentLineCircle(..) => "tangent_line_circle",
            Cons::TangentCircles(..) => "tangent_circles",
            Cons::EqualLength(..) => "equal_length",
            Cons::EqualRadius(..) => "equal_radius",
            Cons::Distance(..) => "distance",
            Cons::DistancePointLine(..) => "distance_point_line",
            Cons::Angle(..) => "angle",
            Cons::Radius(..) => "radius",
            Cons::Diameter(..) => "diameter",
            Cons::Fix(..) => "fix",
            Cons::Midpoint(..) => "midpoint",
            Cons::Symmetric(..) => "symmetric",
        }
    }
}

