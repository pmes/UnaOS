/// One statement. Sketch geometry is plain `[f64; N]` (converted at replay); the Make holds make_core's own types.
#[derive(Clone, Debug, PartialEq)]
pub enum Stmt {
    /// A sketch placed by `Frame::new(o, z, x)` (origin, normal, x hint).
    Sketch { id: String, o: [f64; 3], z: [f64; 3], x: [f64; 3] },
    Point { id: String, sketch: String, at: [f64; 2] },
    Line { id: String, sketch: String, a: String, b: String },
    Circle { id: String, sketch: String, centre: String, r: f64 },
    /// CCW from `start` to `end` (radians).
    Arc { id: String, sketch: String, centre: String, r: f64, start: f64, end: f64 },
    Constraint { id: String, sketch: String, c: Cons },
    /// The profile of the sketch whose outer loop holds the entity `outer`, along `dir` by `length`.
    Extrude { id: String, sketch: String, outer: String, dir: [f64; 3], length: f64 },
    /// The profile selected by `outer`, about the sketch-plane axis (`axis_o`, `axis_d`) by `angle` radians.
    Revolve { id: String, sketch: String, outer: String, axis_o: [f64; 2], axis_d: [f64; 2], angle: f64 },
    Machine(MachineStmt),
    Axis(Axis),
    Tool(Tool),
    Stock(Stock),
    Fixture(Fixture),
    /// An Op on a feature (BP-vug-3); the refused variants are data like the rest.
    Op { id: String, on: String, op: Op },
    Scan { id: String, path: String, pose: Pose, confidence: f64 },
    // VUGFACEFILLET (SR511): a fillet / chamfer of the feature `on`'s edges, each edge named by its persistent brep_core
    // `Name` (written as four words `[op role a b]`), resolved by replay against the feature's replayed solid.
    /// brep_core `fillet` of radius `r` on the edges named `edges` of the solid of `on` (a feature or an earlier edit).
    Fillet { id: String, on: String, edges: Vec<brep_core::Name>, r: f64 },
    /// brep_core `chamfer`: `d1` along the face whose co-edge runs with the edge, `d2` along the other.
    Chamfer { id: String, on: String, edges: Vec<brep_core::Name>, d1: f64, d2: f64 },
    // VUGDOCPHOTOREF (SR652): the photo the document was drawn over, `photo path="<file>" pitch=<mm>` — id-less, one per
    // document, referencing nothing; the path is relative to the document's folder and is data, never opened here
    // (BP-vug-4): the face opens it. The crop meta rides the photo itself; the camera's prefs are Principia's.
    /// The graph-paper photo under the document: its file (relative to the document) and the paper's pitch (mm).
    /// VUGDOCPHOTOREFCROP (SR660): `h=[9 numbers]`, optional — the frame the document was drawn in, row-major paper mm ->
    /// pixel of the NAMED file's pixels (a crop re-measured alone numbers its lattice from its own first line, so its
    /// frame cannot be recovered from it); absent, the named file's own measurement frames the document (SR652's road).
    Photo { path: String, pitch_mm: f64, h: Option<[f64; 9]> },
}

impl Stmt {
    /// The statement's text id (axis / tool / stock / fixture have none: they are the machine's).
    pub fn id(&self) -> Option<&str> {
        match self {
            Stmt::Sketch { id, .. }
            | Stmt::Point { id, .. }
            | Stmt::Line { id, .. }
            | Stmt::Circle { id, .. }
            | Stmt::Arc { id, .. }
            | Stmt::Constraint { id, .. }
            | Stmt::Extrude { id, .. }
            | Stmt::Revolve { id, .. }
            | Stmt::Op { id, .. }
            | Stmt::Scan { id, .. } | Stmt::Fillet { id, .. } | Stmt::Chamfer { id, .. } => Some(id), // VUGFACEFILLET (SR511)
            Stmt::Machine(m) => Some(&m.id),
            Stmt::Axis(_) | Stmt::Tool(_) | Stmt::Stock(_) | Stmt::Fixture(_) | Stmt::Photo { .. } => None, // VUGDOCPHOTOREF (SR652)
        }
    }

    /// VUGINTENTSETORDER (SR551): every id the statement references, in the reader's key order (`sketch=`, the entity
    /// keys, `on=`; a point reference by its entity, `p1.centre` is `p1`): the one truth of the reference graph. A
    /// sketch, the machine (its `lib=` is a library name, not an id), its axes / tools / stock / fixtures and a scan
    /// reference none.
    pub fn refs(&self) -> Vec<&str> {
        fn p(r: &PRef) -> &str {
            match r {
                PRef::Point(i) | PRef::Centre(i) | PRef::Start(i) | PRef::End(i) => i,
            }
        }
        match self {
            Stmt::Point { sketch, .. } => alloc::vec![sketch.as_str()],
            Stmt::Line { sketch, a, b, .. } => alloc::vec![sketch.as_str(), a.as_str(), b.as_str()],
            Stmt::Circle { sketch, centre, .. } | Stmt::Arc { sketch, centre, .. } => {
                alloc::vec![sketch.as_str(), centre.as_str()]
            }
            Stmt::Extrude { sketch, outer, .. } | Stmt::Revolve { sketch, outer, .. } => {
                alloc::vec![sketch.as_str(), outer.as_str()]
            }
            Stmt::Constraint { sketch, c, .. } => {
                let mut v: Vec<&str> = alloc::vec![sketch.as_str()];
                match c {
                    Cons::Coincident(a, b) | Cons::Distance(a, b, _) => v.extend([p(a), p(b)]),
                    Cons::PointOnLine(a, e)
                    | Cons::PointOnCircle(a, e)
                    | Cons::DistancePointLine(a, e, _)
                    | Cons::Midpoint(a, e) => v.extend([p(a), e.as_str()]),
                    Cons::Horizontal(e) | Cons::Vertical(e) | Cons::Radius(e, _) | Cons::Diameter(e, _) => {
                        v.push(e.as_str())
                    }
                    Cons::Parallel(a, b)
                    | Cons::Perpendicular(a, b)
                    | Cons::TangentLineCircle(a, b)
                    | Cons::TangentCircles(a, b)
                    | Cons::EqualLength(a, b)
                    | Cons::EqualRadius(a, b)
                    | Cons::Angle(a, b, _) => v.extend([a.as_str(), b.as_str()]),
                    Cons::Fix(a, _) => v.push(p(a)),
                    Cons::Symmetric(a, b, e) => v.extend([p(a), p(b), e.as_str()]),
                }
                v
            }
            Stmt::Op { on, .. } | Stmt::Fillet { on, .. } | Stmt::Chamfer { on, .. } => alloc::vec![on.as_str()],
            Stmt::Sketch { .. }
            | Stmt::Machine(_)
            | Stmt::Axis(_)
            | Stmt::Tool(_)
            | Stmt::Stock(_)
            | Stmt::Fixture(_)
            | Stmt::Scan { .. } | Stmt::Photo { .. } => Vec::new(), // VUGDOCPHOTOREF (SR652)
        }
    }
}

/// The document: the header's `Tol` and the statements in order. `lines` is where each statement was read; equality
/// ignores it, so a hand edit that adds a comment or reorders keys reads to the same `Doc`.
#[derive(Clone, Debug)]
pub struct Doc {
    pub tol: Tol,
    pub stmts: Vec<Stmt>,
    pub lines: Vec<u32>,
}

impl PartialEq for Doc {
    fn eq(&self, o: &Doc) -> bool {
        self.tol == o.tol && self.stmts == o.stmts
    }
}

impl Doc {
    pub fn new(tol: Tol) -> Doc {
        Doc { tol, stmts: Vec::new(), lines: Vec::new() }
    }

    /// The 1-based line of statement `i`: where it was read, or (built in code) the line [`write`] puts it on.
    pub fn line(&self, i: usize) -> u32 {
        self.lines.get(i).copied().unwrap_or(i as u32 + 2)
    }
}

/// A read that did not happen: the line, the 1-based byte column, and what.
#[derive(Clone, Debug, PartialEq)]
pub struct Refusal {
    pub line: u32,
    pub col: u32,
    pub what: What,
}

/// Every way [`read`] says no, by name.
#[derive(Clone, Debug, PartialEq)]
pub enum What {
    /// The first statement is not `vug-doc ...` (or the text holds no statement).
    NoHeader,
    /// A version this crate does not read.
    Version(u32),
    /// A verb that is not `[a-z][a-z0-9_-]*`.
    BadVerb,
    UnknownVerb(String),
    /// An id that is not `[A-Za-z0-9_-]+`, a statement that needs an id without one, or one that takes none with one.
    BadId,
    DuplicateId(String),
    /// A reference to an id not declared on an earlier line.
    UnknownRef(String),
    /// A sketch reference to an entity of another sketch.
    CrossSketch(String),
    /// A reference to an id of the wrong kind of statement (`sketch=` not a sketch, `on=` not a feature, an entity
    /// reference that names no entity).
    WrongTarget(String),
    /// A string or a list that does not close on its line.
    Unterminated,
    /// A backslash escape outside the one rule.
    BadEscape,
    BadNumber,
    /// `nan` / `inf`: the writer writes them so `write` is total; the reader refuses them.
    NonFinite,
    /// A value of the wrong shape or an unknown word for its key.
    BadValue { key: String },
    UnknownKey(String),
    DuplicateKey(String),
    MissingKey(&'static str),
    /// A second machine statement: one machine per document (VUG-DOC-SETUPS owed).
    SecondMachine,
    /// A second stock for the one machine.
    SecondStock,
    /// An axis / tool / stock / fixture before the machine it belongs to.
    Orphan,
    /// A token where `key=value` is expected.
    Trailing,
    // VUGMAKEMACHINELIB (SR544): a machine from a library.
    /// `machine <id> lib=<name>`: the resolver holds no library of this name.
    UnknownLib(String),
    /// The library `name` did not read; `at` is the refusal inside it (its own line and column).
    BadLib { name: String, at: Box<Refusal> },
    /// A library statement other than the one machine first (without `loaded`) and its axes / tools, or no machine.
    NotLibrary,
    /// VUGDOCPHOTOREF (SR652): a second `photo` statement: one photo per document.
    SecondPhoto,
}

