special_upper, special_lower = {}, {}
for f in lines('SpecialCasing.txt'):
    cond = f[4] if len(f) > 4 and f[4] else ''
    if cond: continue  # Final_Sigma and language-sensitive mappings are handled in code
    cp = int(f[0], 16)
    lo = [int(x, 16) for x in f[1].split()]
    up = [int(x, 16) for x in f[3].split()]
    if lo != [cp] and lo != [lower.get(cp, cp)] or len(lo) != 1: special_lower[cp] = lo
    if len(up) != 1 or up != [upper.get(cp, cp)]: special_upper[cp] = up
fold_simple = {}
fold_full = {}
for f in lines('CaseFolding.txt'):
    cp = int(f[0], 16)
    st = f[1]
    m = [int(x, 16) for x in f[2].split()]
    if st in ('C', 'S'): fold_simple[cp] = m[0]
    if st in ('C', 'F'): fold_full[cp] = m
def pairs(d):
    ks = sorted(d)
    return [x for k in ks for x in (k, d[k])]
def multi(d):
    ks = sorted(d)
    idx, data = [], []
    for k in ks:
        idx += [k, len(data), len(d[k])]
        data += d[k]
    return idx, data
out = [HEADER, "//! Case mapping: simple mappings from UnicodeData (sorted [cp, mapped] pairs), the unconditional\n//! SpecialCasing entries ([cp, offset, len] into *_DATA), and CaseFolding (C+S simple).\n"]
for name, d in (('UPPER', upper), ('LOWER', lower), ('FOLD', fold_simple)):
    p = pairs(d)
    out.append(f"pub static SIMPLE_{name}: [u32; {len(p)}] = [\n{flat(p, 16)}\n];\n")
for name, d in (('UPPER', special_upper), ('LOWER', special_lower)):
    idx, data = multi(d)
    out.append(f"pub static SPECIAL_{name}: [u32; {len(idx)}] = [\n{flat(idx, 18)}\n];\n")
    out.append(f"pub static SPECIAL_{name}_DATA: [u32; {len(data)}] = [\n{flat(data, 16)}\n];\n")
with open(os.path.join(OUT, 'case.rs'), 'w') as f:
    f.write(''.join(out))

