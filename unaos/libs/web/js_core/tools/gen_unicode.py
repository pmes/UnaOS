out = [HEADER, "//! General_Category: ranges as flat [start, end, category] triples covering U+0000..U+10FFFF.\n"]
out.append("pub static GC_NAMES: [&str; %d] = [%s];\n" % (len(GC_ORDER), ', '.join('"%s"' % c for c in GC_ORDER)))
