idx, data = [], []
for cp in sorted(decomp):
    compat, d = decomp[cp]
    idx += [cp, (len(data) << 6) | (len(d) << 1) | (1 if compat else 0)]
    data += d
out.append(f"/// [cp, offset<<6 | len<<1 | compat] pairs.\npub static DECOMP: [u32; {len(idx)}] = [\n{flat(idx, 16)}\n];\n")
out.append(f"pub static DECOMP_DATA: [u32; {len(data)}] = [\n{flat(data, 16)}\n];\n")
cp_ = sorted(comp.items())
nums = [x for (a, b), c in cp_ for x in (a, b, c)]
out.append(f"/// [first, second, composite] sorted by (first, second).\npub static COMPOSE: [u32; {len(nums)}] = [\n{flat(nums, 18)}\n];\n")
