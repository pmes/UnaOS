#!/usr/bin/env python3
"""JSCORE (SR55): generate src/unicode/*.rs from the Unicode Character Database, version 17.0.0.

Usage: python3 tools/gen_unicode.py <ucd-dir>
The UCD files are fetched (by URL, sha256-pinned in tools/ucd.txt) from the unicode-org/unicodetools repository,
which carries the released UCD under unicodetools/data/ucd/17.0.0 (unicode.org itself is not reachable from the
build cloud). Nothing here is hand-edited: every table in src/unicode/ is this script's output.
"""
import sys, os, re, hashlib

UCD = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'unicode')
MAXCP = 0x10FFFF

def lines(name):
    with open(os.path.join(UCD, name), encoding='utf-8') as f:
        for ln in f:
            ln = ln.split('#', 1)[0].strip()
            if ln:
                yield [x.strip() for x in ln.split(';')]

def cprange(s):
    if '..' in s:
        a, b = s.split('..')
        return int(a, 16), int(b, 16)
    v = int(s, 16)
    return v, v

def to_ranges(cps):
    cps = sorted(set(cps))
    out = []
    for c in cps:
        if out and out[-1][1] + 1 == c:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out

def norm_ranges(rs):
    rs = sorted(rs)
    out = []
    for a, b in rs:
        if out and out[-1][1] + 1 >= a:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    return out

def flat(nums, per=16):
    s = []
    for i in range(0, len(nums), per):
        s.append('    ' + ','.join(str(n) for n in nums[i:i + per]) + ',')
    return '\n'.join(s)

HEADER = "// GENERATED by tools/gen_unicode.py from the Unicode Character Database 17.0.0 — do not edit.\n"

