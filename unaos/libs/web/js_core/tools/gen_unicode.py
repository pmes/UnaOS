ccc = {}
decomp = {}
rows = list(lines('UnicodeData.txt'))
i = 0
while i < len(rows):
    f = rows[i]
    cp = int(f[0], 16)
    if f[1].endswith('First>'):
        end = int(rows[i + 1][0], 16)
