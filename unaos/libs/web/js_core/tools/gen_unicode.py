for p in order:
    nums = []
    for s in seqs[p]:
        nums.append(len(s)); nums += s
    out.append(f"pub static S_{p.upper()}: [u32; {len(nums)}] = [\n{flat(nums, 16)}\n];\n")
out.append("pub static STRING_PROPERTIES: [(&str, &[u32]); %d] = [\n" % len(order))
