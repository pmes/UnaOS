def add_prop_file(name, wanted=None):
    for f in lines(name):
        if len(f) < 2: continue
        p = f[1]
        if wanted is not None and p not in wanted: continue
        a, b = cprange(f[0])
        props.setdefault(p, []).append((a, b))

