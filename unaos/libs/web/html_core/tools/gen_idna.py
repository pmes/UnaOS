#!/usr/bin/env python3
"""URLCORE (SR87): generate src/url/idna_tables.rs — the Unicode data UTS #46 processing needs.

Usage:
    python3 tools/gen_idna.py [IdnaMappingTable.txt] > src/url/idna_tables.rs

Inputs (all Unicode 16.0.0 — the version is checked, a mismatch refuses to generate):
  * the UTS #46 IDNA Mapping Table: the file given on the command line (IdnaMappingTable.txt from
    https://www.unicode.org/Public/idna/16.0.0/), or, when no file is given, the same table as the PyPI `idna`
    package (>= 3.10) carries it (`idna.uts46data`, generated by that package from IdnaMappingTable.txt);
  * Joining_Type (DerivedJoiningType.txt), for the CheckJoiners ContextJ rule, from `idna.idnadata.joining_types`;
  * the UCD properties NFC and the validity criteria read — Canonical_Combining_Class, canonical
    Decomposition_Mapping (+ the composition exclusions, derived as "the pair does not recompose under NFC"),
    Bidi_Class and General_Category=Mark — from `unicodedata2` 16.0.0 (`pip install unicodedata2==16.0.0`), or
    from the stdlib `unicodedata` when its unidata_version is 16.0.0.

The output is DATA ONLY. UseSTD3ASCIIRules is false in every WHATWG URL call ("domain to ASCII" with
beStrict = false; the strict path's STD3 check is an ASCII rule applied in code), so the pre-16.0
disallowed_STD3_valid / disallowed_STD3_mapped statuses fold to valid / mapped here, which is what 16.0's
table already says.
"""
import sys, hashlib

UNICODE = "16.0.0"

try:
    import unicodedata2 as ucd
except ImportError:
    import unicodedata as ucd
if ucd.unidata_version != UNICODE:
    sys.exit("gen_idna: need UCD %s, have %s (pip install unicodedata2==%s)" % (UNICODE, ucd.unidata_version, UNICODE))

VALID, IGNORED, MAPPED, DEVIATION, DISALLOWED = 0, 1, 2, 3, 4
MAXCP = 0x110000

# ---------------------------------------------------------------- the mapping table, as [(start, status, mapping)]
rows = []
if len(sys.argv) > 1:
    raw = open(sys.argv[1], "rb").read()
    src = "%s sha256 %s" % (sys.argv[1].rsplit("/", 1)[-1], hashlib.sha256(raw).hexdigest())
    text = raw.decode("utf-8")
    if ("Version: " + UNICODE) not in text and ("IdnaMappingTable-" + UNICODE) not in text:
        sys.exit("gen_idna: %s is not the %s table" % (sys.argv[1], UNICODE))
    status_of = {"valid": VALID, "ignored": IGNORED, "mapped": MAPPED, "deviation": DEVIATION,
                 "disallowed": DISALLOWED, "disallowed_STD3_valid": VALID, "disallowed_STD3_mapped": MAPPED}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(";")]
        lo, _, hi = f[0].partition("..")
        lo = int(lo, 16)
        st = status_of[f[1]]
        mapping = "".join(chr(int(h, 16)) for h in f[2].split()) if len(f) > 2 and st in (MAPPED,) else ""
        rows.append((lo, st, mapping))
else:
    import idna, idna.uts46data as u46
    if u46.__version__ != UNICODE:
        sys.exit("gen_idna: idna.uts46data is %s, need %s" % (u46.__version__, UNICODE))
    src = "PyPI idna %s idna.uts46data (UTS #46 %s IdnaMappingTable.txt)" % (idna.__version__, u46.__version__)
    code = {"V": VALID, "I": IGNORED, "M": MAPPED, "D": DEVIATION, "X": DISALLOWED, "3": None}
    for r in u46.uts46data:
        st = code[r[1]]
        mapping = r[2] if len(r) > 2 else ""
        if st is None:  # disallowed_STD3_*: valid when unmapped, mapped otherwise (UseSTD3ASCIIRules=false)
            st = MAPPED if len(r) > 2 else VALID
        if st != MAPPED:
            mapping = ""  # a deviation's mapping is the transitional one; WHATWG is nontransitional
        rows.append((r[0], st, mapping))

rows.sort()
# Merge neighbours that say the same thing (ranges, not per-code-point rows).
merged = []
for r in rows:
    if merged and merged[-1][1] == r[1] and merged[-1][2] == r[2] and r[1] != MAPPED:
        continue
    if merged and merged[-1][1] == r[1] == MAPPED and merged[-1][2] == r[2]:
        continue
    merged.append(r)
assert merged[0][0] == 0

pool, offsets = [], {}
def intern(s):
    if s not in offsets:
        offsets[s] = sum(len(x.encode("utf-8")) for x in pool)
        pool.append(s)
    return offsets[s]
map_rows = []
for lo, st, m in merged:
    off = intern(m) if st == MAPPED else 0
    n = len(m.encode("utf-8")) if st == MAPPED else 0
    assert n < 256
    map_rows.append((lo, st, off, n))
pool_str = "".join(pool)
assert len(pool_str.encode("utf-8")) < 65536

# ---------------------------------------------------------------- UCD properties
def ranges(prop, skip):
    out, cur = [], None
    for cp in range(MAXCP):
        v = prop(cp)
        if v == skip:
            if cur:
                out.append(cur)
                cur = None
            continue
        if cur and cur[2] == v and cur[1] == cp - 1:
            cur = (cur[0], cp, v)
        else:
            if cur:
                out.append(cur)
            cur = (cp, cp, v)
    if cur:
        out.append(cur)
    return out

def ch(cp):
    return chr(cp) if not 0xD800 <= cp <= 0xDFFF else None

ccc = ranges(lambda cp: ucd.combining(ch(cp)) if ch(cp) else 0, 0)

decomp, compose = [], []
for cp in range(MAXCP):
    c = ch(cp)
    if c is None:
        continue
    d = ucd.decomposition(c)
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    assert 1 <= len(parts) <= 2
    decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    if len(parts) == 2 and ucd.normalize("NFC", chr(parts[0]) + chr(parts[1])) == c:
        compose.append((parts[0], parts[1], cp))
compose.sort()

BIDI = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
        "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
bidi = ranges(lambda cp: BIDI.index(ucd.bidirectional(ch(cp)) or "L") if ch(cp) else 0, 0)

marks = [(a, b) for a, b, _ in ranges(lambda cp: 1 if ch(cp) and ucd.category(ch(cp)).startswith("M") else 0, 0)]

import idna.idnadata as idd
JT = {ord("L"): 1, ord("D"): 2, ord("R"): 3, ord("T"): 4}  # Join_Causing (C) is not in RFC 5892's ContextJ regex
jtab = {cp: JT[v] for cp, v in idd.joining_types.items() if v in JT}
joining = ranges(lambda cp: jtab.get(cp, 0), 0)

# ---------------------------------------------------------------- emit
def lit(s):
    o = []
    for c in s:
        if c.isascii() and (c.isalnum() or c in " !#$%&()*+,-./:;<=>?@[]^_`{|}~'"):
            o.append(c)
        else:
            o.append("\\u{%x}" % ord(c))
    return '"' + "".join(o) + '"'

w = sys.stdout.write
w("// @generated by tools/gen_idna.py — DATA ONLY, do not edit. Unicode %s.\n" % UNICODE)
w("// UTS #46 mapping: %s.\n" % src)
w("// UCD (CCC, canonical decompositions/compositions, Bidi_Class, General_Category=Mark): unicodedata %s.\n" % ucd.unidata_version)
w("// Joining_Type: PyPI idna idna.idnadata.joining_types (DerivedJoiningType.txt %s).\n" % idd.__version__)
w("#![allow(dead_code, clippy::unreadable_literal)]\n\n")
w("pub const VALID: u8 = 0;\npub const IGNORED: u8 = 1;\npub const MAPPED: u8 = 2;\npub const DEVIATION: u8 = 3;\npub const DISALLOWED: u8 = 4;\n\n")
w("/// `(first code point, status, byte offset into MAP_POOL, byte length)`; a row covers up to the next row's start.\n")
w("pub static MAP: &[(u32, u8, u16, u8)] = &[\n")
for r in map_rows:
    w("    (0x%X, %d, %d, %d),\n" % r)
w("];\n\n/// The mapping strings, concatenated.\npub static MAP_POOL: &str = %s;\n\n" % lit(pool_str))
w("/// `(first, last, Canonical_Combining_Class)` for ccc != 0.\npub static CCC: &[(u32, u32, u8)] = &[\n")
for r in ccc:
    w("    (0x%X, 0x%X, %d),\n" % r)
w("];\n\n/// `(code point, first, second or 0)` — canonical Decomposition_Mapping (one level; applied recursively).\n")
w("pub static DECOMP: &[(u32, u32, u32)] = &[\n")
for r in decomp:
    w("    (0x%X, 0x%X, 0x%X),\n" % r)
w("];\n\n/// `(first, second, primary composite)` sorted by `(first, second)` — exclusions already removed.\n")
w("pub static COMPOSE: &[(u32, u32, u32)] = &[\n")
for r in compose:
    w("    (0x%X, 0x%X, 0x%X),\n" % r)
w("];\n\n/// Bidi_Class values, indexed by the third field of BIDI.\n")
w("pub static BIDI_NAMES: &[&str] = &[%s];\n" % ", ".join('"%s"' % b for b in BIDI))
w("/// `(first, last, Bidi_Class index)` for every class other than L (index 0).\npub static BIDI: &[(u32, u32, u8)] = &[\n")
for r in bidi:
    w("    (0x%X, 0x%X, %d),\n" % r)
w("];\n\n/// `(first, last)` with General_Category Mn, Mc or Me.\npub static MARKS: &[(u32, u32)] = &[\n")
for r in marks:
    w("    (0x%X, 0x%X),\n" % r)
w("];\n\n/// `(first, last, Joining_Type)`: 1 = L, 2 = D, 3 = R, 4 = T; absent = U (or C).\npub static JOINING: &[(u32, u32, u8)] = &[\n")
for r in joining:
    w("    (0x%X, 0x%X, %d),\n" % r)
w("];\n")
