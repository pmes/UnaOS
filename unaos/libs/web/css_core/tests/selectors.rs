//! M2 — Selectors Level 4 proven on WPT's matching tests, re-expressed over the test DOM.
//!
//! * dom/nodes/ParentNode-querySelector-All (HTML): selectors.js's invalid selectors (must not parse) and
//!   valid selectors in the Document, In-document Element and Detached Element contexts.
//! * css/selectors: has-basic, has-relative-argument, is-where-basic, is-where-not, not-complex
//!   (`main.querySelectorAll` / `querySelector` / `closest` / `matches`), and
//!   attribute-selectors/attribute-case/semantics (the `i` / `s` flags, standards-mode HTML).
//! Fixtures: tests/wpt/*.json, regenerated by tools/wpt-fixtures.mjs from one pinned WPT commit.
mod common;
