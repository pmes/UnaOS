#!/usr/bin/env python3
"""NETDEBT (LEDGER SR97): generate src/table.rs — the Public Suffix List as psl_core's rule table.

Usage:
    python3 tools/gen_psl.py public_suffix_list.dat > src/table.rs

Input: the Public Suffix List (https://publicsuffix.org/list/public_suffix_list.dat, the same file as
https://github.com/publicsuffix/list main/public_suffix_list.dat), MPL-2.0. It is fetched by hand into a
scratch directory; the generated file records its sha256, so a regeneration from a newer list is one diff.

Format (https://publicsuffix.org/list/ "Formal algorithm"): one rule per line, `//` comments, blank lines;
a rule is a domain (`com`), a wildcard (`*.ck` — the `*` is only ever the leftmost label in the list) or an
exception (`!www.ck`). The ICANN section lies between `===BEGIN ICANN DOMAINS===` and `===END ICANN
DOMAINS===`, the PRIVATE section between `===BEGIN PRIVATE DOMAINS===` and `===END PRIVATE DOMAINS===`.

Output: `RULES: &[(&str, u8)]`, sorted by the bytes of the key, one entry per distinct key — the rule with its
`*.` / `!` removed, every label in its ASCII (A-label) form, lowercase — and a flag byte:
    NORMAL 1   the key is a rule
    WILD   2   `*.key` is a rule
    EXCEPT 4   `!key` is a rule
    PRIVATE 8  a rule on this key came from the PRIVATE section
U-labels are converted with RFC 3492 Punycode (Python's `punycode` codec) behind `xn--`: hosts reach psl_core
already in ASCII form (the WHATWG URL host parser's domain-to-ASCII), so the table is keyed the same way.
"""
import hashlib
import sys

NORMAL, WILD, EXCEPT, PRIVATE = 1, 2, 4, 8


def a_label(label):
    if all(ord(c) < 0x80 for c in label):
        return label.lower()
    return "xn--" + label.lower().encode("punycode").decode("ascii")


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_psl.py public_suffix_list.dat > src/table.rs")
    raw = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    text = raw.decode("utf-8")
    section = None
    rules = {}
    seen = {"icann": 0, "private": 0}
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("//"):
            if "===BEGIN ICANN DOMAINS===" in line:
                section = "icann"
            elif "===BEGIN PRIVATE DOMAINS===" in line:
                section = "private"
            elif "===END ICANN DOMAINS===" in line or "===END PRIVATE DOMAINS===" in line:
                section = None
            continue
        if not line:
            continue
        # The list says a rule ends at the first whitespace.
        rule = line.split()[0]
        if section is None:
            sys.exit("gen_psl: rule outside a section: %r" % rule)
        flag = NORMAL
        if rule.startswith("!"):
            flag, rule = EXCEPT, rule[1:]
        elif rule.startswith("*."):
            flag, rule = WILD, rule[2:]
        if "*" in rule or "!" in rule:
            sys.exit("gen_psl: unsupported rule shape: %r" % line)
        key = ".".join(a_label(l) for l in rule.split("."))
        if not key or any(not l for l in key.split(".")):
            sys.exit("gen_psl: empty label in %r" % line)
        if section == "private":
            flag |= PRIVATE
        rules[key] = rules.get(key, 0) | flag
        seen[section] += 1
    if seen["icann"] < 5000 or seen["private"] < 1000:
        sys.exit("gen_psl: the list looks truncated (%d ICANN, %d PRIVATE rules)" % (seen["icann"], seen["private"]))
    keys = sorted(rules, key=lambda k: k.encode("ascii"))
    out = sys.stdout
    out.write("//! The Public Suffix List as psl_core's rule table (see the crate text for the lookup).\n")
    out.write("//! GENERATED by tools/gen_psl.py from public_suffix_list.dat — do not edit by hand.\n")
    out.write("//! public_suffix_list.dat sha256 %s\n" % digest)
    out.write("//! %d ICANN rules, %d PRIVATE rules, %d keys.\n" % (seen["icann"], seen["private"], len(keys)))
    out.write("//! The list's data: Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/), from\n")
    out.write("//! https://publicsuffix.org/list/public_suffix_list.dat.\n\n")
    out.write("#![allow(clippy::all)]\n\n")
    out.write("pub const NORMAL: u8 = %d;\npub const WILD: u8 = %d;\npub const EXCEPT: u8 = %d;\npub const PRIVATE: u8 = %d;\n\n" % (NORMAL, WILD, EXCEPT, PRIVATE))
    out.write("/// (key, flags), sorted by the key's bytes; binary-searched by `crate::lookup`.\n")
    out.write("pub static RULES: &[(&str, u8)] = &[\n")
    for k in keys:
        out.write('    ("%s", %d),\n' % (k, rules[k]))
    out.write("];\n")


main()
