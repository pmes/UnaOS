/// The 2059 init table for a PHY revision (`radio_2059.c:323-331`: revision 1 only).
pub fn init_table(phy_rev: u16) -> Option<&'static [[u16; 2]]> {
    match phy_rev {
        1 => Some(&r2059_phy_rev1_init),
        _ => None,
    }
}

