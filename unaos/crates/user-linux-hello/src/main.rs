fn main() {
    let out = std::env::args().nth(1).expect("usage: user-linux-hello <HELLO.LNX out-path>");
    let dir = std::path::Path::new(&out).parent().map(|p| p.to_path_buf()).unwrap_or_default();
    for (path, bytes) in [
        (std::path::PathBuf::from(&out), hello()),
        (dir.join("PIPE.LNX"), wrap(PIPE_CODE)),
        (dir.join("LS.LNX"), wrap(LS_CODE)),
    ] {
        std::fs::write(&path, &bytes).expect("write fixture");
        println!("wrote {} ({} bytes)", path.display(), bytes.len());
    }
}
